export async function seedCategories() {
  console.log('Seeding Expense Categories Master...');
  for (const cat of masterCategories) {
    await prisma.expenseCategoryMaster.upsert({
      where: { code: cat.code },
      update: {
        groupCode: cat.groupCode,
        groupName: cat.groupName,
        categoryName: cat.categoryName,
        subcategoryName: cat.subcategoryName,
        receiptRequired: cat.receiptRequired,
        isStatutory: cat.isStatutory || false,
      },
      create: {
        code: cat.code,
        groupCode: cat.groupCode,
        groupName: cat.groupName,
        categoryName: cat.categoryName,
        subcategoryName: cat.subcategoryName,
        receiptRequired: cat.receiptRequired,
        isStatutory: cat.isStatutory || false,
      },
    });
  }
  console.log(`Successfully seeded ${masterCategories.length} master categories.`);
}

if (process.argv[1]?.endsWith('seedCategories.js')) {
  seedCategories()
    .catch((err) => {
      console.error(err);
      process.exit(1);
    })
    .finally(() => prisma.$disconnect());
}
